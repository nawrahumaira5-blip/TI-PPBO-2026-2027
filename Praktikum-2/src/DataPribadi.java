public class DataPribadi {
    public static void main(String[] args) {

        // Menyimpan data umur dalam tipe data integer
        int umur = 20;

        // Menyimpan data tinggi badan dalam tipe data double
        // Double digunakan karena tinggi badan memiliki angka desimal
        double tinggiBadan = 170.5;

        // Menyimpan inisial nama dalam tipe data char
        // Char hanya dapat menyimpan satu karakter
        char inisial = 'M';

        // Menyimpan status mahasiswa aktif dalam tipe data boolean
        // True berarti mahasiswa tersebut masih aktif
        boolean isMahasiswaAktif = true;

        // Menampilkan inisial ke layar
        System.out.println("Inisial: " + inisial);

        // Menampilkan umur ke layar
        System.out.println("Umur: " + umur + " tahun");

        // Menampilkan tinggi badan ke layar
        System.out.println("Tinggi Badan: " + tinggiBadan + " cm");

        // Menampilkan status mahasiswa aktif ke layar
        System.out.println("Status Mahasiswa Aktif: " + isMahasiswaAktif);
    }
}
